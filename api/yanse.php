// ------------------------------------------------------------
// 生成随机颜色函数
// 返回：格式为 #RRGGBB 的十六进制颜色值
// ------------------------------------------------------------
function randomColor() {
    // 使用 sprintf 格式化为6位十六进制数
    return sprintf('#%06X', mt_rand(0, 0xFFFFFF));
}

// ------------------------------------------------------------
// 输出随机颜色
// ------------------------------------------------------------
echo randomColor();
